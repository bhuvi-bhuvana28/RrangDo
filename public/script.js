let selectedQty = {}

// ➕ INCREASE
function increaseQty(name){

  let id = name.replace(/\s/g,'')

  if(!selectedQty[name]){
    selectedQty[name] = 1
  }

  selectedQty[name]++

  document.getElementById("qty-" + id).innerText = selectedQty[name]
}

